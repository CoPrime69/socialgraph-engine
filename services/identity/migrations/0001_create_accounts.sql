-- Accounts of members who can sign in (contracts §4, §10.2, §10.4).
-- Imported Stack Overflow users are graph-service profiles, not accounts; their ids are all below
-- 100,000,000, so member ids start there and the two id spaces never collide.
CREATE TABLE accounts (
  id            bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100000000) PRIMARY KEY,
  handle        text        NOT NULL CONSTRAINT accounts_handle_key UNIQUE
                            CONSTRAINT accounts_handle_format CHECK (handle ~ '^[a-z0-9_]{3,32}$'),
  name          text        NOT NULL CONSTRAINT accounts_name_length CHECK (char_length(name) BETWEEN 1 AND 64),
  password_hash text        NOT NULL CONSTRAINT accounts_password_hash_format CHECK (password_hash LIKE '$argon2id$%'),
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  CONSTRAINT accounts_id_positive CHECK (id > 0)
);

-- Id 100000000 is reserved for the seeded demo member (contracts §10.2): self-registered members
-- get 100000001 onwards whether or not the demo account is seeded, so a graph-service that seeded
-- the demo profile can never be handed a different member under the same id.
SELECT setval(pg_get_serial_sequence('accounts', 'id'), 100000000, true);
